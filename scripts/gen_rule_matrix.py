"""Generate a static, source-linked security inventory; this does not run tests."""

from __future__ import annotations

import argparse
import ast
import hashlib
import runpy
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGES = ("kernel", "stores", "schemas", "crypto", "gateway")
DEFAULT_OUTPUT = ROOT / "docs/submission/rule-matrix.md"


def parse(path: Path) -> ast.Module:
    return ast.parse(path.read_text(encoding="utf-8-sig"), filename=str(path))


def location(path: Path, name: str, line: int) -> str:
    relative = path.relative_to(ROOT).as_posix()
    return f"[`{relative}::{name}`](../../{relative}#L{line})"


def marker_ids(node: ast.AST) -> set[str]:
    result: set[str] = set()
    for item in ast.walk(node):
        if not isinstance(item, ast.Call) or not isinstance(item.func, ast.Attribute):
            continue
        if ast.unparse(item.func) != "pytest.mark.rule":
            continue
        if len(item.args) != 1 or not isinstance(item.args[0], ast.Constant):
            raise ValueError("Nonliteral rule marker requires manual inspection")
        if not isinstance(item.args[0].value, str) or item.keywords:
            raise ValueError("Invalid rule marker")
        result.add(item.args[0].value)
    return result


def test_references(path: Path) -> dict[str, set[str]]:
    result: dict[str, set[str]] = defaultdict(set)

    def visit(node: ast.Module | ast.ClassDef, prefix: str, inherited: set[str]) -> None:
        local = set(inherited)
        for statement in node.body:
            if isinstance(statement, (ast.Assign, ast.AnnAssign)):
                local.update(marker_ids(statement))
        if isinstance(node, ast.ClassDef):
            for decorator in node.decorator_list:
                local.update(marker_ids(decorator))
        for statement in node.body:
            if isinstance(statement, ast.ClassDef):
                visit(statement, prefix + statement.name + "::", local)
            elif isinstance(statement, (ast.FunctionDef, ast.AsyncFunctionDef)):
                rules = set(local)
                for decorator in statement.decorator_list:
                    rules.update(marker_ids(decorator))
                if not statement.name.startswith("test_"):
                    continue
                for rule in rules:
                    result[rule].add(location(path, prefix + statement.name, statement.lineno))

    visit(parse(path), "", set())
    return result


def source_references(path: Path, rules: set[str]) -> dict[str, set[str]]:
    result: dict[str, set[str]] = defaultdict(set)

    def visit(node: ast.AST, scope: str = "module") -> None:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            scope = node.name if scope == "module" else scope + "." + node.name
        if isinstance(node, ast.Constant) and isinstance(node.value, str) and node.value in rules:
            result[node.value].add(location(path, scope, node.lineno))
        for child in ast.iter_child_nodes(node):
            visit(child, scope)

    visit(parse(path))
    return result


def generate() -> str:
    registry_path = ROOT / "src/corridor/kernel/rules.py"
    registry = runpy.run_path(str(registry_path))["RULES"]
    test_files = sorted((ROOT / "tests").rglob("*.py"))
    source_files = sorted(
        path for package in PACKAGES for path in (ROOT / "src/corridor" / package).rglob("*.py")
    )
    tests: dict[str, set[str]] = defaultdict(set)
    references: dict[str, set[str]] = defaultdict(set)
    for path in test_files:
        for rule, values in test_references(path).items():
            tests[rule].update(values)
    for path in source_files:
        if path == registry_path:
            continue
        for rule, values in source_references(path, set(registry)).items():
            references[rule].update(values)
    unknown = set(tests) - set(registry)
    missing = set(registry) - set(tests)
    if unknown or missing:
        raise ValueError(
            f"Unknown markers: {sorted(unknown)}; rules without markers: {sorted(missing)}"
        )
    digest = hashlib.sha256()
    for path in sorted(set(source_files + test_files)):
        digest.update(path.relative_to(ROOT).as_posix().encode("utf-8") + b"\0")
        digest.update(path.read_bytes() + b"\0")
    lines = [
        "# Rule, execution-point and test inventory",
        "",
        "Generated by `python scripts/gen_rule_matrix.py` from the current worktree. "
        "Do not edit this appendix by hand.",
        "",
        f"- Registered rules: **{len(registry)}**; "
        f"rules with literal test markers: **{len(tests)}**.",
        f"- SHA-256 over sorted TCB/test paths and exact bytes: `{digest.hexdigest()}`.",
        "- Scope: the integrated bank and wealth implementation, including ALLOC rules, "
        "approval budgets and suitability lifecycle controls. See the "
        "[assessment](security-self-assessment.md) for threat assumptions and review fixes.",
        "- Execution points below are literal rule references in trusted source, including "
        "propagation and validation sites. A reference alone does not prove reachability.",
        "- Tests below are static decorator/parameter-marker references, not a passing-test "
        "report. Parameterized entries identify the containing test; "
        "pytest selects the marked case.",
        "- Runtime validation is `uv run corridor test --rules-coverage`. The repository plugin "
        "requires a successful executed positive rule assertion; a marker alone is insufficient. "
        "This generator does not replace that gate.",
        "",
        "## Trusted-code inventory",
        "",
        "Counts use the CLI's nonempty, non-comment physical-line convention; docstrings count. "
        "Direct imports are not a transitive dependency or supply-chain inventory. "
        "Standard-library classification uses the interpreter running this generator.",
        "",
        "| Package | Python files | Counted lines | Direct third-party imports |",
        "|---|---:|---:|---|",
    ]
    for package in PACKAGES:
        files = [
            path for path in source_files if path.is_relative_to(ROOT / "src/corridor" / package)
        ]
        count = 0
        dependencies: set[str] = set()
        for path in files:
            count += sum(
                bool(line.strip()) and not line.lstrip().startswith("#")
                for line in path.read_text(encoding="utf-8-sig").splitlines()
            )
            for node in ast.walk(parse(path)):
                names: list[str] = []
                if isinstance(node, ast.Import):
                    names = [alias.name for alias in node.names]
                elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
                    names = [node.module]
                for name in names:
                    top = name.split(".")[0]
                    if top not in sys.stdlib_module_names and top != "corridor":
                        dependencies.add(top)
        lines.append(
            f"| `{package}/` | {len(files)} | {count} | "
            f"{', '.join(sorted(dependencies)) or 'Standard library only'} |"
        )
    lines.extend([
        "",
        "## Registered rules",
        "",
        "| Rule | Registered layer / outcome | Execution-point references | Marked tests |",
        "|---|---|---|---|",
    ])
    for rule, metadata in registry.items():
        source = (
            "<br>".join(sorted(references[rule]))
            or "No literal source reference; inspect propagation"
        )
        test = "<br>".join(sorted(tests[rule]))
        lines.append(
            f"| `{rule}` | {metadata.enforced_by} / {metadata.outcome} | {source} | {test} |"
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the generated file differs")
    args = parser.parse_args()
    text = generate()
    if args.check:
        if not DEFAULT_OUTPUT.exists() or DEFAULT_OUTPUT.read_text(encoding="utf-8") != text:
            print("Rule matrix is missing or stale.")
            return 1
        print("Rule matrix matches the current source and literal test markers.")
        return 0
    DEFAULT_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    DEFAULT_OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Generated {DEFAULT_OUTPUT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
